// scripts/gen-metric-registry.mjs
// Reads every `metric` seed INSERT out of the migrations (in filename order)
// and regenerates packages/strength-engine/src/metric.ts so the SQL seed and
// the TS map cannot drift. Run manually after editing a seed; CI's
// `checks/docs.mjs` pattern does not cover this file, so `metric.test.ts`
// (Task 2) is what actually guards drift.
//
// The `metric` seed is not confined to one migration: 20260818's original
// seed and 20260819's additive `pain` row (moved out of 20260818 because
// that migration may already be applied elsewhere) BOTH contribute rows, so
// this globs every migration under supabase/migrations and concatenates
// whatever `insert into metric (...) values (...);` statements it finds, in
// filename order, rather than hardcoding one path.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const migrationsDir = 'supabase/migrations';
const migrationFiles = readdirSync(migrationsDir)
  .filter(f => f.endsWith('.sql'))
  .sort();

const rows = [];
let matchedAnyFile = false;
for (const file of migrationFiles) {
  const sql = readFileSync(`${migrationsDir}/${file}`, 'utf8');
  const matches = [...sql.matchAll(/insert into metric\s*\([^)]*\)\s*values\s*([\s\S]*?);/gi)];
  for (const match of matches) {
    matchedAnyFile = true;
    for (const [, key, dimension, canonicalUnit, valueType, aggregation, higherIsBetter, isLoadBearing] of
      match[1].matchAll(/\(\s*'([^']+)',\s*'([^']+)',\s*'([^']+)',\s*'([^']+)',\s*'([^']+)',\s*(true|false|null),\s*(true|false)\s*\)/g)) {
      rows.push({
        key, dimension, canonicalUnit, valueType, aggregation,
        higherIsBetter: higherIsBetter === 'null' ? null : higherIsBetter === 'true',
        isLoadBearing: isLoadBearing === 'true',
      });
    }
  }
}
if (!matchedAnyFile) throw new Error('no metric seed INSERT found in any migration');

const keys = rows.map(r => `'${r.key}'`).join(' | ');
const entries = rows.map(r => `  ${r.key}: {
    key: '${r.key}',
    dimension: '${r.dimension}',
    canonicalUnit: '${r.canonicalUnit}',
    valueType: '${r.valueType}',
    aggregation: '${r.aggregation}',
    higherIsBetter: ${r.higherIsBetter === null ? 'null' : r.higherIsBetter},
    isLoadBearing: ${r.isLoadBearing},
  },`).join('\n');

const out = `// GENERATED by scripts/gen-metric-registry.mjs from every metric seed INSERT
// under supabase/migrations/ (in filename order — currently
// 20260818_strength_rebuild.sql and 20260819_phase_e_pain_metric.sql). Do
// not hand-edit — edit the migrations' seed rows and re-run the script.

export type MetricKey = ${keys};

export interface Metric {
  key: MetricKey;
  dimension: string;
  canonicalUnit: string;
  valueType: 'scalar' | 'range' | 'tuple' | 'duration';
  aggregation: 'sum' | 'mean' | 'max' | 'min' | 'last' | 'none';
  higherIsBetter: boolean | null;
  isLoadBearing: boolean;
}

export const METRICS: Record<MetricKey, Metric> = {
${entries}
};
`;

writeFileSync('packages/strength-engine/src/metric.ts', out);
console.log(`Wrote ${rows.length} metrics to packages/strength-engine/src/metric.ts`);
